    private void btnModificaeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificaeActionPerformed
        int id = Integer.parseInt(txtId.getText());

        boolean ok = archivo.modificar(
                id,
                txtNombre.getText(),
                txtDescripcion.getText(),
                Integer.parseInt(txtExistencia.getText())
        );

        JOptionPane.showMessageDialog(this, ok ? "Modificado" : "No encontrado");
        cargarTabla();
        limpiarCajas();
        txtId.requestFocus();
    }//GEN-LAST:event_btnModificaeActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        int id = Integer.parseInt(txtId.getText());

        if (archivo.eliminar(id)) {
            JOptionPane.showMessageDialog(this, "Eliminado");
        } else {
            JOptionPane.showMessageDialog(this, "No encontrado");
        }

        cargarTabla();
        limpiarCajas();
        txtId.requestFocus();
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblListarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblListarMouseClicked
        // TODO add your handling code here:
        int fila = tblListar.getSelectedRow();

        if (fila != -1) {
            txtId.setText(tblListar.getValueAt(fila, 0).toString());
            txtNombre.setText(tblListar.getValueAt(fila, 1).toString());
            txtDescripcion.setText(tblListar.getValueAt(fila, 2).toString());
            txtExistencia.setText(tblListar.getValueAt(fila, 3).toString());

            // 👉 habilitar botones
            habilitarDeshabilitarElimModif(true);
        }
    }//GEN-LAST:event_tblListarMouseClicked

