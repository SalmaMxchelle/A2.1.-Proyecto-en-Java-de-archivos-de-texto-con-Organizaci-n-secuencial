    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        Producto p = new Producto(
                Integer.parseInt(txtId.getText()),
                txtNombre.getText(),
                txtDescripcion.getText(),
                Integer.parseInt(txtExistencia.getText())
        );

        archivo.agregarProducto(p);
        cargarTabla();
        this.limpiarCajas();
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        if (txtId.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe ingresar el ID a buscar");
            txtId.requestFocus();
            return;
        }

        int id = Integer.parseInt(txtId.getText());

        Producto p = archivo.buscar(id);

        if (p != null) {
            txtNombre.setText(p.getNombre());
            txtDescripcion.setText(p.getDescripcion());
            txtExistencia.setText(String.valueOf(p.getExistencia()));

            for (int i = 0; i < tblListar.getRowCount(); i++) {

                if (tblListar.getValueAt(i, 0).toString().equals(String.valueOf(id))) {

                    tblListar.setRowSelectionInterval(i, i);

                    break;
                }
            }
            habilitarDeshabilitarElimModif(true);
        } else {
            JOptionPane.showMessageDialog(this, "No encontrado");
        }

    }//GEN-LAST:event_btnBuscarActionPerformed

